export function auditClean(value: string): string {
  return redactCredentialMaterial(value, '[認証情報を除去]')
    .replace(
      /https:\/\/hooks\.slack\.com\/services\/[^\s\"'<>]+/gi,
      '[認証情報を除去]',
    )
    .replace(
      /(["'](?:password|client_secret|secret|access_token|refresh_token|api[_-]?key|token)["']\s*:\s*)(["'])([^\r\n]*?)\2/gi,
      '$1"[認証情報を除去]"',
    )
    .replace(/sktsec_[A-Za-z0-9_\-]+/g, '[認証情報を除去]')
    .replace(
      /(?:cookie|set-cookie|authorization)\s*[:=][^\r\n]*/gi,
      '[認証ヘッダーを除去]',
    )
    .replace(/<\/?(?:zerokun_files|ZERO_[^>]*)[^>]*>/gi, '[制御文字列を除去]')
}
